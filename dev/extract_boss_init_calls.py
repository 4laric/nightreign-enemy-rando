@dataclass
class CallSpec:
    """One InitializeCommonEvent call extracted from vanilla."""
    slot: int       # the first arg to InitializeCommonEvent, usually 0; layer 1 is rare
    event_id: int   # the common_event being called (e.g. 90065910)
    params: List[int]  # the remaining args, verbatim from vanilla

    def emit_text(self) -> str:
        """DarkScript3 source line."""
        all_args = [str(self.slot), str(self.event_id)] + [str(p) for p in self.params]
        return f"$InitializeCommonEvent({', '.join(all_args)});"


@dataclass
class ArenaEmevdSpec:
    """Test-mode EMEVD for one arena.

    Holds just the calls we want to emit, in the order vanilla had them.
    No boss-spec / region-eid structure — we don't transform the call
    args, we copy them verbatim.
    """
    map_short_name: str  # e.g. 'm48_90_00_00'
    calls: List[CallSpec] = field(default_factory=list)


# ───────────────────────────────────────────────────────────────────
# Extraction from vanilla EMEVD source
# ───────────────────────────────────────────────────────────────────


# Match $InitializeCommonEvent(slot, event_id, arg1, arg2, ...);
# Slot can be 0 or 1 (layer marker). Event ID is 6-9 digits.
# Args can be any integers (possibly negative).
_CALL_RE = re.compile(
    r'\$InitializeCommonEvent\s*\(\s*'
    r'(\d+)\s*,\s*'           # slot
    r'(\d+)\s*'                # event_id
    r'((?:\s*,\s*-?\d+(?:\.\d+)?)*)'  # zero or more args (we'll strip .0)
    r'\s*\)\s*;?'
)


def extract_calls(vanilla_emevd_js: str) -> List[CallSpec]:
    """Parse a vanilla per-map EMEVD .js source and return all the
    boss-init / death-observer InitializeCommonEvent calls we want to
    preserve in the test-mode overlay.

    The order is preserved (matches vanilla's emit order).
    """
    out: List[CallSpec] = []
    for m in _CALL_RE.finditer(vanilla_emevd_js):
        slot = int(m.group(1))
        event_id = int(m.group(2))
        if not _should_keep_event(event_id):
            continue
        rest = m.group(3).strip()
        if rest.startswith(','):
            rest = rest[1:]
        params: List[int] = []
        if rest:
            for p in rest.split(','):
                p = p.strip()
                if not p:
                    continue
                # Some args may be floats like 0.55; truncate to int
                # since the EMEVD wire format stores everything as uint32
                # and DarkScript3 emits floats only as a DSL convenience.
                # The bit pattern matters; for InitializeCommonEvent args,
                # vanilla writes them as raw uint32 bits.
                if '.' in p:
                    # Float param — encode bits as uint32 via struct
                    f = float(p)
                    bits = struct.unpack('<I', struct.pack('<f', f))[0]
                    params.append(bits)
                else:
                    n = int(p)
                    if n < 0:
                        # Negative int → two's complement uint32
                        n = n & 0xFFFFFFFF
                    params.append(n)
        out.append(CallSpec(slot=slot, event_id=event_id, params=params))
    return out


# ───────────────────────────────────────────────────────────────────
# Emit — text and binary
# ───────────────────────────────────────────────────────────────────


def emit_text(spec: ArenaEmevdSpec) -> str:
    """Generate a DarkScript3 .emevd.js source for the test-mode EMEVD.

    Single $Event(0, Default, ...) containing all kept calls in order.
    """
    lines = [
        "// ==EMEVD==",
        "// @docs    nr-common.emedf.json",
        "// @compress    DCX_KRAK",
        f"// @generated {spec.map_short_name} test-mode (v0.26.1)",
        f"// {len(spec.calls)} boss-init/death-observer calls preserved from vanilla",
        "// ==/EMEVD==",
        "",
        "$Event(0, Default, function() {",
    ]
    for c in spec.calls:
        lines.append(f"    {c.emit_text()}")
    lines.append("});")
    lines.append("")
    return "\n".join(lines)


def emit_binary(spec: ArenaEmevdSpec) -> bytes:
    """Generate raw .emevd binary (Sekiro+ format).

    Uses the synth.py builder. The builder accepts any event_id /
    arg-count combination because InitializeCommonEvent is just a
    flat-args record (class=2000, index=0, then N uint32 args).
    """
    import sys
    _here = os.path.dirname(os.path.abspath(__file__))
    _hb_path = os.path.join(_here, '..', 'healthbar_inplace')
    if _hb_path not in sys.path:
        sys.path.insert(0, _hb_path)
    from synth import build_minimal_emevd, healthbar_instruction

    instructions = []
    for c in spec.calls:
        # healthbar_instruction(slot, common_event_id, *params) builds
        # the args list as [slot, common_event_id, *params] and returns
        # an InitializeCommonEvent record. Name is historical (it was
        # built for the healthbar parser test fixtures).
        instructions.append(healthbar_instruction(c.slot, c.event_id, *c.params))

    events_spec = [{
        'event_id': 0,
        'rest_behavior': 0,  # Default
        'instructions': instructions,
    }]
    return build_minimal_emevd(events_spec)


# ───────────────────────────────────────────────────────────────────
# CLI
# ───────────────────────────────────────────────────────────────────


def main():
    import argparse
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--vanilla-emevd-js', required=True,
                     help='Vanilla per-map EMEVD .js source')
    ap.add_argument('--map-name', required=True,
                     help='Map short name (e.g. m48_90_00_00)')
    ap.add_argument('--out-js', help='Write text emit here')
    ap.add_argument('--out-bin', help='Write binary emit here (.emevd, pre-DCX)')
    args = ap.parse_args()

    with open(args.vanilla_emevd_js) as f:
        vsrc = f.read()
    calls = extract_calls(vsrc)
    if not calls:
        print(f'WARNING: no boss-init calls extracted from {args.vanilla_emevd_js}')
    spec = ArenaEmevdSpec(map_short_name=args.map_name, calls=calls)

    print(f'Extracted {len(calls)} calls from {args.vanilla_emevd_js}:')
    for c in calls[:10]:
        print(f'  {c.emit_text()}')
    if len(calls) > 10:
        print(f'  ... +{len(calls)-10} more')

    if args.out_js:
        with open(args.out_js, 'w') as f:
            f.write(emit_text(spec))
        print(f'Text emit -> {args.out_js}')
    if args.out_bin:
        with open(args.out_bin, 'wb') as f:
            f.write(emit_binary(spec))
        print(f'Binary emit -> {args.out_bin}')


def _scan_disable_chr_events(common_func_js_path: str) -> set:
    """Regenerate DISABLE_CHR_EVENTS by scanning common_func.emevd.js.

    Run this if vanilla NR updates change the 9006xxxx event bodies.
    Print the result and paste it into the DISABLE_CHR_EVENTS literal at
    the top of this file.

    Usage:
      python3 -c "from dev.extract_boss_init_calls import _scan_disable_chr_events; \\
                  print(sorted(_scan_disable_chr_events('path/to/common_func.emevd.js')))"
    """
    with open(common_func_js_path) as f:
        src = f.read()
    event_re = re.compile(r'\$Event\((\d+),\s*\w+,\s*function[^)]*\)\s*\{', re.DOTALL)
    out = set()
    for m in event_re.finditer(src):
        eid = int(m.group(1))
        if not 90065000 <= eid <= 90069999:
            continue
        start = m.end()
        depth, i = 1, start
        while i < len(src) and depth > 0:
            if src[i] == '{': depth += 1
            elif src[i] == '}': depth -= 1
            i += 1
        body = src[start:i-1]
        if 'DisableCharacter' in body[:1500]:
            out.add(eid)
    return out


if __name__ == '__main__':
    main()
