#!/usr/bin/env python3
"""extract_boss_init_calls.py — derive minimal test-mode EMEVDs by COPYING
the boss-init calls verbatim from vanilla per-map EMEVDs, stripping the
events that disable the boss chr at map-load.

v0.26.1 design (replaces v0.25.x's prefix-based KEEP filter).

The fundamental discovery (May 19 2026)
========================================
Earlier versions assumed vanilla NR boss Parts started DISABLED in the
MSB and were ENABLED by the per-map EMEVD at night-1. Direct comparison
of vanilla witchy'd XMLs to MMV references showed this is wrong:

    | Field                  | Vanilla m48_20 | MMV m46_56  |
    |------------------------|----------------|-------------|
    | GameEditionDisable     | NeverDisable   | NeverDisable|
    | MapStudioLayer         | 4294967295     | 4294967295  |
    | Condition1 / Condition2| 0 / 0          | 0 / 0       |
    | ChrActivateCondParamID | 0              | 0           |

Vanilla NR boss MSB Parts are STRUCTURALLY IDENTICAL to MMV's
NeverDisable Parts on every "alive at map-load" candidate field.

So where does the vanilla boss-disable come from? Entirely from EMEVD.
Specifically, 90065910 (and its multi-phase variants 90065131, 90065121,
90065050, etc.) call `DisableCharacter(chrEntityId)` at event 0, BEFORE
waiting for the night-1 flag. The chr is alive in the MSB but the
EMEVD immediately disables it at game start.

v0.26.1 strategy
================
Since the MSB is already correct (NeverDisable), the test mode is purely
about stripping the events that disable the chr. The new filter:

  KEEP, by default:
    - 9006xxxx — except events that contain DisableCharacter in their body
      (see DISABLE_CHR_EVENTS below). Notably 90065911 (cleanup) and
      90065900 (post-death enable) are KEPT.
    - 9005xxxx — night-1 flag setter fallback (90055000/001)
    - 9003xxxx — asset toggles tied to night-1
    - 90015002 — combat aggro + healthbar UI when player engages
    - 90015008 — death observer (sets the night-2 cleanup flag)
    - 90015012 — multiplayer combat-scaling SpEffect
    - 90015015/016 — chr SpEffect setters (specific Limveld tiles)
    - 90015020 — multiplayer status flag
    - 90015030 — idle anim
    - 90015442 — PRIMARY night-1 flag setter (tile→arena translator,
      v0.25.10's miss)
    - 90015443 — paired arena flag-setter

  STRIP:
    - All chr-disabler events (DISABLE_CHR_EVENTS set, computed by
      scanning common_func.emevd.js for events whose body contains
      DisableCharacter)
    - 90015070 — cinematic frame triggers (original test-mode goal)
    - Everything else not in the keep set

Result: chr alive at day-1 (MSB NeverDisable, no EMEVD disable), boss
is fightable immediately, on death + night-1-flag the cleanup fires and
night-2 progresses normally. The only behavioral cost vs vanilla is
no "dramatic night-1 appearance" — chr is already standing there. For
test mode that's a feature; iteration is much faster.

Tradeoff worth noting: no boss BGM transition (90065910 set the music),
and boss healthbar visibility depends on 90015002 firing (which it does
when player enters combat range).
"""
from __future__ import annotations

import os
import re
import struct
from dataclasses import dataclass, field
from typing import List, Optional


# v0.26.1: hardcoded list of 9006xxxx events whose body contains
# DisableCharacter. These get STRIPPED from test-mode overlays so the
# chr stays alive from map-load (the MSB Part is already NeverDisable).
# Generated by scanning common_func.emevd.js — regenerate if vanilla
# updates change the event bodies (see _scan_disable_chr_events helper
# at the bottom of this file).
DISABLE_CHR_EVENTS = frozenset({
    90065000, 90065001, 90065002, 90065009, 90065014, 90065031,
    90065040, 90065050, 90065051, 90065052, 90065053, 90065056, 90065057,
    90065061, 90065062, 90065064, 90065070, 90065082, 90065090,
    90065100, 90065110, 90065120, 90065121, 90065122,
    90065130, 90065131, 90065132,
    90065201, 90065211, 90065215, 90065216, 90065220, 90065221,
    90065251, 90065252, 90065254,
    90065910, 90065912,
})

# Events we explicitly KEEP regardless of prefix-based rules.
# 90015002: combat aggro + healthbar UI when player engages
# 90015008: death observer — sets post-kill flag for night-2
# 90015012: multiplayer combat-scaling SpEffect
# 90015015/016: chr SpEffect setters (specific Limveld tiles)
# 90015020: multiplayer status flag
# 90015030: idle anim (cosmetic but cheap)
# 90015442: PRIMARY night-1 flag setter (tile→arena translator).
#           This was the v0.25.10 miss — chain broke because no flag
#           was getting set. Kept now.
# 90015443: paired arena flag-setter
KEEP_EVENT_EXPLICIT = frozenset({
    90015002, 90015008, 90015012, 90015015, 90015016,
    90015020, 90015030, 90015442, 90015443,
})

# Prefix-based keep — keep all 9005xxxx (night-1 flag fallback path)
# and 9003xxxx (asset toggles tied to night-1 progression).
# 9006xxxx is conditionally kept (see _should_keep_event).
KEEP_EVENT_PREFIXES = ('9005', '9003')


def _should_keep_event(event_id: int) -> bool:
    """Return True if the event_id should be preserved in the test-mode EMEVD.

    Rules (in order):
      1. If in DISABLE_CHR_EVENTS — STRIP (these disable the boss chr).
      2. If in KEEP_EVENT_EXPLICIT — KEEP.
      3. If 9006xxxx (and not in DISABLE_CHR_EVENTS by rule 1) — KEEP.
         These are 9006xxxx events that don't disable chrs: 90065911
         (cleanup), 90065900 (post-death), and similar.
      4. If matches a KEEP_EVENT_PREFIXES prefix — KEEP.
      5. Otherwise — STRIP.
    """
    if event_id in DISABLE_CHR_EVENTS:
        return False
    if event_id in KEEP_EVENT_EXPLICIT:
        return True
    eid_str = str(event_id)
    if eid_str.startswith('9006'):
        return True
    for prefix in KEEP_EVENT_PREFIXES:
        if eid_str.startswith(prefix):
            return True
    return False


