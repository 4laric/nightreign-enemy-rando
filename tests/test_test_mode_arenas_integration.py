def test_v0_26_1_strips_chr_disabler_events():
    """v0.26.1: every chr-disabler event from DISABLE_CHR_EVENTS must be
    absent from every test-mode arena. This is the new core invariant —
    by stripping these we keep the boss alive at map-load (MSB Part is
    NeverDisable) so the player can fight it during day-1 instead of
    waiting for night-1.

    The full set is 38 events; we spot-check the most common ones across
    the 19 arenas.
    """
    sys.path.insert(0, os.path.join(_ROOT, 'dev'))
    from extract_boss_init_calls import DISABLE_CHR_EVENTS

    inv_path = os.path.join(_ROOT, 'dev', 'test_mode_arenas', '_inventory.json')
    with open(inv_path) as f:
        inv = json.load(f)

    leaks = []
    for entry in inv['generated']:
        eids = set(entry.get('event_ids', []))
        leak = eids & DISABLE_CHR_EVENTS
