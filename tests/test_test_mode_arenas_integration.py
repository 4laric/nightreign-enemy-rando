# ---------------------------------------------------------------------
# Test-mode arenas overlay a minimal lifecycle EMEVD that spawns
# whatever chr the MSB has at the XXXX0800 entity slot. For the boss to
# be RANDOMIZED (not vanilla), that slot must be in V3_BOSS_SLOT_CATALOG
# so the picker swaps it. Four arenas (m47_80/m47_90/m48_00/m48_10)
# regressed here once: data/nr_all_slots.json + nr_boss_slots.json were
# built from a stale MSB snapshot missing the c7700/c7710/c7800/c7820
# boss parts, so the catalog had zero slots for them and test-mode runs
# showed vanilla bosses. This test locks in full coverage.

def test_all_test_mode_arenas_have_catalogued_boss_slot():
    """Every one of the 19 test-mode arenas must have at least one
    chr slot in V3_BOSS_SLOT_CATALOG, otherwise its boss can't be
    randomized and test-mode shows the vanilla boss."""
    sys.path.insert(0, _ROOT)
    import oops_v3
    if not oops_v3.V3_BOSS_SLOT_CATALOG:
        oops_v3.load_data()
    cat = oops_v3.V3_BOSS_SLOT_CATALOG

    inv_path = os.path.join(_ROOT, 'dev', 'test_mode_arenas', '_inventory.json')
    with open(inv_path) as f:
        inv = json.load(f)
    arenas = [e['arena'] + '.msb' for e in inv['generated']]

    uncovered = []
    for arena in arenas:
        chr_slots = [(m, p) for (m, p) in cat
                     if m == arena and cat[(m, p)].get('cp')]
        if not chr_slots:
            uncovered.append(arena)

    assert not uncovered, (
        f"{len(uncovered)} test-mode arena(s) have NO catalogued boss "
        f"slot — their bosses will spawn vanilla, not randomized: "
        f"{uncovered}. Likely cause: data/nr_all_slots.json or "
        f"nr_boss_slots.json is stale. Regenerate nr_all_slots.json "
        f"from dev/all_msb_slots.json.")
