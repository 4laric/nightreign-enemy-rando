def test_test_mode_arena_binaries_parse_via_emevd_module():
    """The healthbar_inplace EMEVD parser must accept each binary.

    This is the critical structural validation — if the binary is
    well-formed enough to parse, it's much more likely to be loaded
    correctly by the game's runtime."""
    sys.path.insert(0, os.path.join(_ROOT, 'healthbar_inplace'))
    try:
        from emevd import EMEVD
    except ImportError:
        # healthbar_inplace not available in test environment — skip
        return

    test_mode_dir = os.path.join(_ROOT, 'dev', 'test_mode_arenas')
    n_parsed = 0
    failures = []
    for fn in sorted(os.listdir(test_mode_dir)):
        if not fn.endswith('.emevd'): continue
        try:
            with open(os.path.join(test_mode_dir, fn), 'rb') as f:
                raw = f.read()
            parsed = EMEVD.parse(raw)
            # Must have at least one event
            assert len(parsed.events) >= 1, f"{fn}: no events"
            # Event 0 must have instructions
            assert len(parsed.events[0].instructions) > 0, (
                f"{fn}: event 0 empty")
            n_parsed += 1
        except Exception as e:
            failures.append((fn, str(e)))

    assert not failures, (
        f"Parse failures ({len(failures)} of {n_parsed + len(failures)}):\n"
        + "\n".join(f"  {fn}: {err}" for fn, err in failures[:5]))
    assert n_parsed == 19, f"Expected 19 parseable files, got {n_parsed}"


