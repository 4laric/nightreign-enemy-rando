def test_v0_26_1_header_layout_matches_soulsformats_spec():
    """v0.26.1: Every generated .emevd must have the SoulsFormats-compatible
    header. Specifically:
        @0x00 = b'EVD\\x00' (magic)
        @0x04 = b'\\x00\\xff\\x01\\xff' (Sekiro+ varint mode flags)
        @0x08 = 0xCD (version int for Sekiro/ER/NR)
        @0x0C = file_size as u32

    Pre-v0.26.1 synth.py wrote file_size at 0x08 and 0 at 0x0C, which is
    what DS3-era tooling and SoulsFormats reject with:
        "Read Int32: <file_size> | Expected: 0xCC, 0xCD | Ending position: 0xC"

    This regression test catches if the bug ever creeps back in."""
    import struct
    test_mode_dir = os.path.join(_ROOT, 'dev', 'test_mode_arenas')
    failures = []
    for fn in sorted(os.listdir(test_mode_dir)):
        if not fn.endswith('.emevd'):
            continue
        with open(os.path.join(test_mode_dir, fn), 'rb') as f:
            data = f.read()
        magic = data[0:4]
        flags = data[4:8]
        version = struct.unpack_from('<I', data, 0x08)[0]
        file_size = struct.unpack_from('<I', data, 0x0C)[0]
        if magic != b'EVD\x00':
            failures.append(f'{fn}: magic {magic!r} != EVD\\x00')
        if flags != b'\x00\xff\x01\xff':
            failures.append(f'{fn}: flags {flags.hex()} != 00ff01ff')
        if version != 0xCD:
            failures.append(f'{fn}: version 0x{version:x} != 0xCD (Sekiro+/NR)')
        if file_size != len(data):
            failures.append(f'{fn}: file_size {file_size} != actual {len(data)}')
    assert not failures, (
        "EMEVD header layout regressions (would be rejected by SoulsFormats "
        "and likely by the game's loader too):\n  " + "\n  ".join(failures))


def test_v0_25_9_extractor_handles_float_args():
    """Vanilla EMEVDs use float args in some calls (e.g. 90015008 in
    m48_90 passes 0.55 as the targetAmount). Our extractor must encode
    the float's bit pattern as uint32 since the EMEVD wire format
    stores everything as uint32 and the bits matter semantically.

    Regression for: dropping float args would change behavior; encoding
    them as int(0.55)=0 would silently change the death threshold from
    55% HP to 0%."""
    import importlib.util
    spec_loader = importlib.util.spec_from_file_location(
        'extract_boss_init_calls',
        os.path.join(_ROOT, 'dev', 'extract_boss_init_calls.py'))
    mod = importlib.util.module_from_spec(spec_loader)
    sys.modules['extract_boss_init_calls'] = mod  # required for dataclass resolution
    spec_loader.loader.exec_module(mod)

    # m48_90 has: 90015008(0, 48900205, 48900800, 921200, 48900800, 0, 0.55)
    vp = '/home/claude/vanilla_emevd/vanilla_decompressed_emevd/m48_90_00_00.emevd.js'
    if not os.path.exists(vp):
        return  # skip if vanilla source isn't available in this env
    with open(vp) as f:
        vsrc = f.read()
    calls = mod.extract_calls(vsrc)
    # Find the 90015008 call
    deaths = [c for c in calls if c.event_id == 90015008]
    assert deaths, "m48_90 should have a 90015008 call"
    # The 0.55 float bit pattern is 1057803469 (0x3F19999A)
    import struct
    expected_bits = struct.unpack('<I', struct.pack('<f', 0.55))[0]
    assert expected_bits == 1057803469
    # Last arg of the 90015008 call should be the bits, not int(0.55)=0
    last_arg = deaths[0].params[-1]
    assert last_arg == expected_bits, (
        f"Float arg 0.55 in 90015008 not encoded as bit pattern: "
        f"got {last_arg}, expected {expected_bits}. "
        f"Dropping float bits silently changes the boss-death threshold.")


